const assert=require('node:assert/strict'),live=require('../live-data.js');
const now=Date.parse('2026-11-19T08:00:00Z');
const wind={id:'met-1',name:'Coastal wind',lat:60.8,lon:17.4,readings:{wind:{value:7.2,time:now,provisional:true},windDirection:{value:240,time:now}}};
const wave={id:'sea-2',name:'Wave buoy',lat:60.9,lon:18,readings:{wave:{value:1.2,time:now}}};
const data={schema:1,checked:new Date(now).toISOString(),stations:[wind,wave]};
const offshore={...wind,id:'met-4',lat:59,lon:20};
const inland={...wind,id:'met-5',lat:60.42,lon:15.5};
const lake={...wave,id:'sea-6',lat:58.93,lon:13.34};
assert.deepEqual(live.coastal([wind,wave,offshore,inland,lake]).map(s=>s.id),['met-1','sea-2','met-4']);
assert.equal(live.stations({...data,stations:[inland,lake]},now).length,2,'Map filtering must not remove stations from details or nearby lists');
assert.equal(live.stations(data,now).length,2);
assert.equal(live.stations(data,now+3*3600000).length,0);
assert.equal(live.nearby(live.stations(data,now),{lat:60.85,lon:17.58},'wind')[0].station.id,'met-1');
assert.equal(live.nearby(live.stations(data,now),{lat:60.85,lon:17.58},'waves')[0].station.id,'sea-2');
assert.equal(live.stations({...data,stations:[{...wind,readings:{wind:{value:7,time:now-3*3600000}}}]},now).length,0);
assert.equal(live.format('wind',7.2),'7.2 m/s');assert.equal(live.format('wave',1.2),'1.2 m');
assert.equal(live.format('level',-17),'-17 cm');assert.equal(live.format('windDirection',240),'240°');
const temperature={id:'sea-9',name:'Temperature buoy',lat:60.9,lon:18,readings:{temperature:{value:6.05,time:now,depth:0}}};
assert.equal(live.stations({...data,stations:[temperature]},now)[0].readings.temperature.value,6.05);
assert.equal(live.stations({...data,stations:[{...temperature,readings:{temperature:{value:6,time:now,depth:5}}}]},now).length,0);
assert.equal(live.format('temperature',6.05),'6.0 °C');
console.log('Live observation checks passed: per-reading freshness, station types, nearest wind/wave stations, observed units and local-mean levels.');

const viva={id:'viva-33',vivaId:'33',owner:'Sjöfartsverket · ViVa',name:'Bönan',lat:60.73,lon:17.32,readings:{temperature:{value:5.4,time:now,source:'viva',depth:null}}};
const normalized=live.stations({...data,stations:[viva]},now)[0];
assert.equal(normalized.id,'viva-33');assert.equal(normalized.vivaId,'33');assert.equal(normalized.readings.temperature.depth,null);assert.equal(normalized.readings.temperature.source,'viva');
assert.equal(live.stations({...data,stations:[{...viva,readings:{temperature:{...viva.readings.temperature,depth:5}}}]},now).length,0);

const fmi={...viva,id:'fmi-134246',name:'Selkämeri aaltopoiju',readings:{temperature:{value:6.5,time:now,source:'fmi',depth:null},wave:{value:1.2,time:now,source:'fmi',provisional:true}}};
const finnish=live.stations({...data,stations:[fmi]},now)[0];assert.equal(finnish.id,'fmi-134246');assert.equal(finnish.readings.temperature.source,'fmi');assert.equal(finnish.readings.wave.provisional,true);
