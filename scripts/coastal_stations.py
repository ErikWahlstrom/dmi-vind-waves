"""Generate the Live map mask from Natural Earth 10 m land and coastlines.

Run from the checkout with the forecast renderer dependencies installed.
"""

import base64
from pathlib import Path
from textwrap import wrap

from cartopy.io import shapereader
import numpy as np
from pyproj import Transformer
import shapely
from shapely.ops import transform


def clipped_geometries(name, bounds):
    path = shapereader.natural_earth(resolution="10m", category="physical", name=name)
    reader = shapereader.Reader(path, bbox=bounds.bounds)
    try:
        return [geometry.intersection(bounds) for geometry in reader.geometries()]
    finally:
        reader.close()


def main():
    west, south, east, north, scale = 9, 53, 32, 70, 20
    width, height = (east - west) * scale, (north - south) * scale
    bounds = shapely.box(west - 1, south - 1, east + 1, north + 1)
    lon, lat = np.meshgrid(west + (np.arange(width) + .5) / scale,
                           south + (np.arange(height) + .5) / scale)

    land = shapely.union_all(clipped_geometries("land", bounds))
    shapely.prepare(land)
    at_sea = ~shapely.contains_xy(land, lon, lat)

    project = Transformer.from_crs("EPSG:4326", "EPSG:3035", always_xy=True).transform
    coast = transform(project, shapely.union_all(clipped_geometries("coastline", bounds)))
    coastal_land = coast.buffer(15_000)
    shapely.prepare(coastal_land)
    x, y = project(lon, lat)
    visible = at_sea | shapely.contains_xy(coastal_land, x, y)
    encoded = base64.b64encode(np.packbits(visible, bitorder="little")).decode("ascii")
    lines = ",\n        ".join(f'"{line}"' for line in wrap(encoded, 100))
    output = Path(__file__).resolve().parents[1] / "coastal-stations.js"
    output.write_text(f"""/* Generated by scripts/coastal_stations.py from Natural Earth 10 m land and coastlines. */
(function(root){{
    'use strict';
    var mask={{west:{west},south:{south},scale:{scale},width:{width},height:{height},bits:[
        {lines}
    ].join('')}};
    if(typeof module==='object'&&module.exports)module.exports=mask;
    else root.ForecastCoastalMask=mask;
}})(typeof window==='object'?window:globalThis);
""", encoding="utf-8")


if __name__ == "__main__":
    main()
